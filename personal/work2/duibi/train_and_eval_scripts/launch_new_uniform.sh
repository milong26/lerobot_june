#!/bin/bash
# Launch state-space uniform experiment in tmux
# Usage: bash launch_new_uniform.sh <gpu_id> <dataset_name> [dataset_path]
# 新的uniform，之前那个只能做到grasp成功，没有实现全空间。
# 第三个参数可选：数据集路径，默认为 /data/zhonglinye/jun/lerobot/personal/work2/dataset_view/pick_place_<dataset_name>

set -e

GPU_ID=${1:-0}
DATASET_NAME=${2:-corner3}
DATASET_PATH=${3:-/data/zhonglinye/jun/lerobot/personal/work2/dataset_view/pick_place_${DATASET_NAME}}

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

OUTPUT_BASE_DIR="/data/zhonglinye/jun/lerobot/personal/work2/duibi/state_uniform_42_${DATASET_NAME}"
LOG_DIR="$OUTPUT_BASE_DIR/logs"

EXP_NAME="state_uniform_112_seed42"
TMUX_SESSION="state_uniform_112_s42_${DATASET_NAME}"

mkdir -p "$LOG_DIR"

# Save dataset path config for train_and_eval.sh
echo "$DATASET_PATH" > "$OUTPUT_BASE_DIR/dataset_path.txt"
echo "Dataset path saved: $DATASET_PATH"

tmux kill-session -t $TMUX_SESSION 2>/dev/null || true

RUNNER_SCRIPT="$LOG_DIR/${EXP_NAME}_runner.sh"

cat > "$RUNNER_SCRIPT" << RUNNER_EOF
#!/bin/bash

eval "\$(conda shell.bash hook 2>/dev/null)"
conda activate lb_server

export PYTHONUNBUFFERED=1

cd /data/zhonglinye/jun/lerobot

EXP_NAME="state_uniform_112_seed42"

GPU_ID=\$1
DATASET_NAME=\$2
DATASET_PATH=\$3

OUTPUT_BASE_DIR="/data/zhonglinye/jun/lerobot/personal/work2/duibi/state_uniform_42_\${DATASET_NAME}"

LOG_DIR="\$OUTPUT_BASE_DIR/logs"

TIME_FILE="\$LOG_DIR/\$EXP_NAME.time"
PID_FILE="\$LOG_DIR/\$EXP_NAME.pid"

TRAIN_SCRIPT="/data/zhonglinye/jun/lerobot/personal/work2/duibi/train_and_eval_scripts/train_and_eval.sh"

mkdir -p "\$LOG_DIR"

# Save dataset path config
echo "\$DATASET_PATH" > "\$OUTPUT_BASE_DIR/dataset_path.txt"

echo \$\$ > "\$PID_FILE"

echo "Start time: \$(date '+%Y-%m-%d %H:%M:%S')" > "\$TIME_FILE"
echo "PID: \$\$" >> "\$TIME_FILE"

echo "========================================"
echo "Experiment: \$EXP_NAME"
echo "Sampling: state-space coverage uniform"
echo "GPU: \$GPU_ID"
echo "Dataset: \$DATASET_NAME"
echo "Dataset Path: \$DATASET_PATH"
echo "PID: \$\$"
echo "Started: \$(date '+%Y-%m-%d %H:%M:%S')"
echo "========================================"
echo ""

# state_uniform:
# dataset generated by:
# reset state space coverage
# -> valid state filtering
# -> adaptive perturbation
# -> episode collection

bash "\$TRAIN_SCRIPT" state_uniform 112 42 \$GPU_ID "\$OUTPUT_BASE_DIR" "\$DATASET_NAME" 2>&1 | tee -a "\$LOG_DIR/\$EXP_NAME.log"


echo "" >> "\$TIME_FILE"
echo "End time: \$(date '+%Y-%m-%d %H:%M:%S')" >> "\$TIME_FILE"
echo "Status: completed" >> "\$TIME_FILE"


echo ""
echo "========================================"
echo "Experiment completed: \$EXP_NAME"
echo "Finished: \$(date '+%Y-%m-%d %H:%M:%S')"
echo "========================================"

exec bash

RUNNER_EOF

chmod +x "$RUNNER_SCRIPT"


tmux new-session -d -s $TMUX_SESSION "bash $RUNNER_SCRIPT $GPU_ID $DATASET_NAME $DATASET_PATH"


echo "Launched experiment: $EXP_NAME"
echo "tmux session: $TMUX_SESSION"
echo "Output dir: $OUTPUT_BASE_DIR"
echo "Dataset: $DATASET_NAME"
echo "Dataset Path: $DATASET_PATH"
echo ""
echo "Monitor with:"
echo "tmux attach -t $TMUX_SESSION"
echo ""
echo "Check logs:"
echo "tail -f $LOG_DIR/$EXP_NAME.log"