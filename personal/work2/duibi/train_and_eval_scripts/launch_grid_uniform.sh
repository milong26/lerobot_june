#!/bin/bash
# Launch grid-based obj-goal joint-region uniform experiment in tmux
# Usage: bash launch_grid_uniform.sh --gpu <gpu_id> --episodes <num_episodes> --dataset <dataset_name> [--dataset-path <dataset_path>]
# 新的grid_uniform：obj_init_pos空间独立分区 × goal_pose空间独立分区 → 联合区域均匀分配

set -e

# Parse command line arguments with -- markers
GPU_ID=""
NUM_EPISODES=""
DATASET_NAME=""
DATASET_PATH=""

while [[ $# -gt 0 ]]; do
    case $1 in
        --gpu)
            GPU_ID="$2"
            shift 2
            ;;
        --episodes)
            NUM_EPISODES="$2"
            shift 2
            ;;
        --dataset)
            DATASET_NAME="$2"
            shift 2
            ;;
        --dataset-path)
            DATASET_PATH="$2"
            shift 2
            ;;
        *)
            echo "Unknown parameter: $1"
            echo "Usage: bash launch_grid_uniform.sh --gpu <gpu_id> --episodes <num_episodes> --dataset <dataset_name> [--dataset-path <dataset_path>]"
            exit 1
            ;;
    esac
done

# Set defaults if not provided
GPU_ID=${GPU_ID:-0}
NUM_EPISODES=${NUM_EPISODES:-112}
DATASET_NAME=${DATASET_NAME:-disassemble-v3_corner}
DATASET_PATH=${DATASET_PATH:-/data/zhonglinye/jun/lerobot/personal/work2/dataset_view/${DATASET_NAME}}

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

OUTPUT_BASE_DIR="/data/zhonglinye/jun/lerobot/personal/work2/duibi/grid_uniform_ep${NUM_EPISODES}_seed42_${DATASET_NAME}"
LOG_DIR="$OUTPUT_BASE_DIR/logs"

EXP_NAME="grid_uniform_${NUM_EPISODES}_seed42"
TMUX_SESSION="grid_uniform_ep${NUM_EPISODES}_s42_${DATASET_NAME}"

mkdir -p "$LOG_DIR"

# Save dataset path config for train_and_eval.sh
echo "$DATASET_PATH" > "$OUTPUT_BASE_DIR/dataset_path.txt"
echo "Dataset path saved: $DATASET_PATH"

tmux kill-session -t $TMUX_SESSION 2>/dev/null || true

RUNNER_SCRIPT="$LOG_DIR/${EXP_NAME}_runner.sh"

cat > "$RUNNER_SCRIPT" << RUNNER_EOF
#!/bin/bash

eval "\$(conda shell.bash hook 2>/dev/null)"
conda activate lb_server

export PYTHONUNBUFFERED=1

cd /data/zhonglinye/jun/lerobot

GPU_ID=\$1
NUM_EPISODES=\$2
DATASET_NAME=\$3
DATASET_PATH=\$4

EXP_NAME="grid_uniform_\${NUM_EPISODES}_seed42"

OUTPUT_BASE_DIR="/data/zhonglinye/jun/lerobot/personal/work2/duibi/grid_uniform_ep\${NUM_EPISODES}_seed42_\${DATASET_NAME}"

LOG_DIR="\$OUTPUT_BASE_DIR/logs"

TIME_FILE="\$LOG_DIR/\$EXP_NAME.time"
PID_FILE="\$LOG_DIR/\$EXP_NAME.pid"

TRAIN_SCRIPT="/data/zhonglinye/jun/lerobot/personal/work2/duibi/train_and_eval_scripts/train_and_eval.sh"

mkdir -p "\$LOG_DIR"

# Save dataset path config
echo "\$DATASET_PATH" > "\$OUTPUT_BASE_DIR/dataset_path.txt"

echo \$\$ > "\$PID_FILE"

echo "Start time: \$(date '+%Y-%m-%d %H:%M:%S')" > "\$TIME_FILE"
echo "PID: \$\$" >> "\$TIME_FILE"

echo "========================================"
echo "Experiment: \$EXP_NAME"
echo "Sampling: factorized obj-goal joint-region uniform"
echo "GPU: \$GPU_ID"
echo "Episodes: \$NUM_EPISODES"
echo "Dataset: \$DATASET_NAME"
echo "Dataset Path: \$DATASET_PATH"
echo "PID: \$\$"
echo "Started: \$(date '+%Y-%m-%d %H:%M:%S')"
echo "========================================"
echo ""

# grid_uniform:
# dataset generated by:
# reset state space coverage
# -> valid state filtering
# -> adaptive perturbation
# -> episode collection
#
# Selection algorithm:
# 1. Extract obj_init_pos and goal_pose from episodes
# 2. Find active dimensions for each space
# 3. Generate K_obj and K_goal uniform region centers (farthest-point sampling)
# 4. Assign episodes to (obj_region, goal_region) joint regions
# 5. Allocate balanced quotas across valid joint regions
# 6. Select episodes closest to joint region centers

bash "\$TRAIN_SCRIPT" grid_uniform \$NUM_EPISODES 42 \$GPU_ID "\$OUTPUT_BASE_DIR" "\$DATASET_NAME" 2>&1 | tee -a "\$LOG_DIR/\$EXP_NAME.log"


echo "" >> "\$TIME_FILE"
echo "End time: \$(date '+%Y-%m-%d %H:%M:%S')" >> "\$TIME_FILE"
echo "Status: completed" >> "\$TIME_FILE"


echo ""
echo "========================================"
echo "Experiment completed: \$EXP_NAME"
echo "Finished: \$(date '+%Y-%m-%d %H:%M:%S')"
echo "========================================"

exec bash

RUNNER_EOF

chmod +x "$RUNNER_SCRIPT"


tmux new-session -d -s $TMUX_SESSION "bash $RUNNER_SCRIPT $GPU_ID $NUM_EPISODES $DATASET_NAME $DATASET_PATH"


echo "Launched experiment: $EXP_NAME"
echo "tmux session: $TMUX_SESSION"
echo "Output dir: $OUTPUT_BASE_DIR"
echo "Dataset: $DATASET_NAME"
echo "Dataset Path: $DATASET_PATH"
echo "Episodes: $NUM_EPISODES"
echo ""
echo "Monitor with:"
echo "tmux attach -t $TMUX_SESSION"
echo ""
echo "Check logs:"
echo "tail -f $LOG_DIR/$EXP_NAME.log"
